def rgb(c):
    return "%d, %d, %d" % c


def bursts_for_colour(name, c):
    """The coloured sparks and glows everything else is built from. Tinted from the default particle
    the way energy_sparks_plasma is, so no new art and no borrowed art."""
    return [
        "burst %s_snap   # a %s muzzle snap: a short hard spray of coloured light" % (name, name.split("_")[-1]),
        "  count   = 9", "  cone    = 22", "  speed   = 190, 0.5", "  life    = 0.07, 0.3",
        "  color   = %s" % rgb(c), "  glow    = 3.6", "  size    = 0.9, 0.3", "  drag    = 3.0",
        "  orient  = streak", "  stretch = 0.02", "  aim     = along", "end", "",
        "burst %s_spark   # coloured sparks off whatever it struck" % name,
        "  count   = 16", "  cone    = 64", "  speed   = 240, 0.55", "  life    = 0.24, 0.4",
        "  color   = %s" % rgb(c), "  glow    = 2.6", "  size    = 0.6, 0.3", "  drag    = 2.2",
        "  orient  = streak", "  stretch = 0.03", "end", "",
        "burst %s_glow   # the flash of the hit itself: a soft ball of its own colour, gone at once" % name,
        "  count   = 2", "  cone    = 0", "  speed   = 0, 0", "  life    = 0.10, 0.25",
        "  color   = %s" % rgb(c), "  glow    = 4.0", "  size    = 3.2, 0.3", "end", "",
    ]


