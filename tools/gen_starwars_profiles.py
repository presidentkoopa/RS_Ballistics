def check_sounds(body):
    declared = set()
    for line in io.open(SND, encoding="utf-8", errors="replace"):
        t = line.split("//")[0].strip()
        for kw in ("$random", "$alias", "$playersound", "$limit", "$pitchset", "$volume"):
            if t.lower().startswith(kw):
                t = t[len(kw):].strip()
                break
        m = re.match(r"^([A-Za-z0-9_/\-]+)", t)
        if m:
            declared.add(m.group(1).lower())
    bad = []
    for ln in body:
        m = re.match(r"^\s*(sound|tail|whiz)\s*=\s*(?:\d+\s*,\s*)?([A-Za-z0-9_/\-]+)", ln)
        if not m:
            continue
        n = m.group(2).lower()
        if n in ("none", "") or n in declared or (n + "/int") in declared or (n + "/ext") in declared:
            continue
        bad.append(m.group(2))
    if bad:
        raise SystemExit("REFUSING TO WRITE: not declared in SNDINFO, would be silent:\n  "
                         + "\n  ".join(sorted(set(bad))))


def skins():
    """Recolour btracer.png: the white-hot core kept, the orange edge swapped for each bolt colour.
    GENERATED from this package's own texture -- no new art and nothing borrowed."""
    from PIL import Image
    src = Image.open(os.path.join(PKG, "models", "bullet", "btracer.png")).convert("RGBA")
    for colour, (r, g, b) in BOLT.items():
        im = src.copy()
        px = im.load()
        w, h = im.size
        for y in range(h):
            for x in range(w):
                pr, pg, pb, pa = px[x, y]
                if pa == 0:
                    continue
                white = min(pr, pg, pb) / 255.0       # how much of this pixel is the hot core
                bright = max(pr, pg, pb) / 255.0
                nr = int(255 * white + r * bright * (1 - white))
                ng = int(255 * white + g * bright * (1 - white))
                nb = int(255 * white + b * bright * (1 - white))
                px[x, y] = (min(255, nr), min(255, ng), min(255, nb), pa)
        im.save(os.path.join(PKG, "models", "bullet", "bolt_%s.png" % colour))


