#!/usr/bin/env python3
"""
gen_blood_profiles.py -- Blood's guns get their own ballistics.

All eight Blood guns were firing in someone else's clothes: the flare gun on a rocket flash and a .45
recoil, the Life Leech on a plasma rifle. The owner: "some of the blood weapons are iconic".

THIS PASS IS THE TWO THAT SHARE A PROBLEM NOTHING IN THE PACKAGE HAD -- a shot whose work STARTS when
it lands instead of resolving there:

  BL_FlareGun   sticks in what it hits and keeps burning. Blood's signature opener.
  BL_Lighter    thrown, tumbles, lands, and burns where it stops -- "lights people on fire like the
                flaregun". Same problem, so the same answer.

WHERE THE FIRE COMES FROM. The owner first said to pull burning sprites out of Bloom and corrected
himself in the same breath: "or don't pull sprites because the blood engine knows what fire damage
is". He is right and it is the better answer -- flame_body, flame_core, flame_licks, flame_tip,
flame_embers, flame_smoke and ember_metal are all this package's own, and a burning man is a
COMPOSITION of them. No source art is taken from anything.

WHAT IS NOT HERE, on purpose. The fire does no HEALTH damage: that is the gun's, the same boundary
that keeps a cartridge from deciding a weapon's damage. `damage` on a hotspot is a scorch brush --
what the fire does to the WALL -- and that one is mine.

    python tools/gen_blood_profiles.py
"""
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFS = os.path.join(HERE, "..", "RSBDEFS.txt")
SND = os.path.join(HERE, "..", "SNDINFO.txt")
BEGIN = "# ---- BEGIN BLOOD (generated by tools/gen_blood_profiles.py) ----"
END = "# ---- END BLOOD ----"

# ---------------------------------------------------------------- the flare, as a real cartridge
# A 26.5 mm flare: a 35 g star lobbed at about 250 fps on a small charge. Low velocity and a lot of
# mass, which is why it reads as a soft heavy shove rather than a crack, and why it flies slowly
# enough to watch. Same free-recoil arithmetic as every other gun in the package.
FLARE_GRAINS, FLARE_FPS, FLARE_CHARGE, FLARE_ROUND = 540, 250, 4.0, 900
FLARE_LB = 2.70          # the sheet's baseweight for BL_FlareGun
ACTION_SEMI = 1.15
CLIMB_PER_FPS = 0.148


def free_recoil(grains, fps, charge, lb):
    vg = (grains * fps + 4700.0 * charge) / (7000.0 * lb)
    return vg, lb * vg * vg / 64.348, lb * vg / 32.174


def blocks():
    vg, energy, impulse = free_recoil(FLARE_GRAINS, FLARE_FPS, FLARE_CHARGE, FLARE_LB)
    climb = vg * CLIMB_PER_FPS * ACTION_SEMI
    out = [BEGIN, ""]

    # ------------------------------------------------------------ THE FIRE ITSELF
    # One hit sets it to full heat and it burns down from there: heat = <per hit>, <cool/s>, <max>,
    # so 1.60 / 0.11 is about fourteen seconds of fire from a single flare.
