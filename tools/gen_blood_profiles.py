        "# heats a spot on a wall and the spot stays on the wall, which is right for a saw and wrong for",
        "# a fire. Riding, a spot fed by a shot that landed on a THING follows that thing: a burning man",
        "# burns while he runs and carries his own light with him.",
        "#",
        "# ONE HIT SETS IT TO FULL and it burns down: 1.60 of heat against 0.11 a second is about",
        "# fourteen seconds. Nothing feeds it again, which is the whole point -- the shot has left.",
        "hotspot bl_burn            # a flare buried in something, burning it down",
        "  ride       = yes",
        "  merge      = 40",
        "  heat       = 1.60, 0.11, 1.60",
        "  bursts     = flame_body 14, flame_core 9, flame_licks 7, flame_tip 5, flame_embers 4, flame_smoke 6",
        "  light      = 130, 2.4",
        "  lightcolor = 255, 138, 48",
