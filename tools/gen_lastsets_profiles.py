def free_recoil(wb, vb, wc, lb):
    vg = (wb * vb + 4700.0 * wc) / (7000.0 * lb)
    return vg, lb * vg * vg / 64.348, lb * vg / 32.174


def recoil_blocks():
    out = []
    for gid in DERIVED:
        wb, vb, wc, empty, cap, rgr, action, note = DERIVED[gid]
        loaded = empty + cap * (rgr / 7000.0)
        vg, e, imp = free_recoil(wb, vb, wc, loaded)
        climb = min(CLIMB_CEILING, vg * CLIMB_PER_FPS * ACTION[action])
        # THE COMPENSATOR. A brake vents gas up and sideways and takes a real bite out of muzzle rise
        # -- that is what it is FOR, and on the Auto 9 it is most of the gun. This is the only place
        # in the package where a mechanical feature, not a mass, changes the kick, so it is stated
        # here with its reason rather than folded into a fudged action multiplier.
        brake = 0.62 if gid == "rc_auto9" else 1.0
        climb *= brake
        out += ["recoil %s   # %s -- %.1f ft-lb, Vg %.2f fps, impulse %.3f lb-s%s"
                % (gid, note, e, vg, imp, ", compensator takes 38%" if brake < 1 else ""),
                "  climb   = %.2f" % climb,
                "  shot    = %.2f, %.1f, %.3f" % (vg, e, imp),
                "  drift   = %.2f, %d" % (0.30 if action != "belt" else 0.22, 5),
                "  recover = %d, %d" % (int(max(8, min(30, 26 * (3.0 / max(1.0, climb)) ** 0.3))), 6),
                "  max     = %.1f, %.1f" % (max(3.0, min(10.0, 3.0 + 2.2 * climb)),
                                            max(2.0, 1.0 + 1.1 * climb)),
                "  bloom   = 0.02",
                "  brace   = 0.6, 0.85",
                "  view    = %.1f, %d, 1, %d" % (1.0 + 1.2 * (climb / 2.6),
                                                 4 + int(4 * (climb / 2.6)), 6),
                "end", ""]
    for gid in STATED:
        climb, drift, period, rec, delay, maxp, maxy, note = STATED[gid]
        out += ["recoil %s   # %s -- STATED: no cartridge to derive from" % (gid, note),
                "  climb   = %.2f" % climb,
                "  drift   = %.2f, %d" % (drift, period),
                "  recover = %d, %d" % (rec, delay),
                "  max     = %.1f, %.1f" % (maxp, maxy),
                "  bloom   = 0.00",
                "  brace   = 0.6, 0.85",
                "  view    = %.1f, %d, 1, %d" % (1.0 + 1.2 * (climb / 2.6),
                                                 4 + int(4 * (climb / 2.6)), 8),
                "end", ""]
    return out


