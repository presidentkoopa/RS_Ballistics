def check_sounds(body):
    """Refuse to write a sound name SNDINFO does not declare. A dead sound name is silent and fine."""
    declared = set()
    for line in io.open(SND, encoding="utf-8", errors="replace"):
        t = line.split("//")[0].strip()
        for kw in ("$random", "$alias", "$playersound", "$limit", "$pitchset", "$volume"):
            if t.lower().startswith(kw):
                t = t[len(kw):].strip()
                break
        m = re.match(r"^([A-Za-z0-9_/\-]+)", t)
        if m:
            declared.add(m.group(1).lower())
    bad = []
    for ln in body:
        m = re.match(r"^\s*(sound|tail)\s*=\s*([A-Za-z0-9_/\-]+)", ln)
        if not m:
            continue
        n = m.group(2).lower()
        if n in ("none", "") or n in declared:
            continue
        if (n + "/int") in declared or (n + "/ext") in declared:
            continue
        bad.append(m.group(2))
    if bad:
        raise SystemExit("REFUSING TO WRITE: not declared in SNDINFO and would be silent:\n  "
                         + "\n  ".join(sorted(set(bad))))


